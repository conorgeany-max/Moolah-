const pt = (p: P) => `${p[0]},${p[1]}`

function lines(pose: Pose) {
  return {
    torso: [pose.N, pose.P],
    arm: [pose.N, pose.E, pose.W],
    leg: [pose.P, pose.K, pose.A, pose.T ?? pose.A],
    arm2: [pose.N, pose.E2 ?? pose.E, pose.W2 ?? pose.W],
    leg2: [pose.P, pose.K2 ?? pose.K, pose.A2 ?? pose.A, pose.T2 ?? pose.T ?? pose.A],
  }
}

export function ExerciseFigure({ figure, animated = true, className, label }: { figure: FigureKey; animated?: boolean; className?: string; label?: string }) {
  const def = F[figure] ?? F.squat
  const la = lines(def.a)
  const lb = lines(def.b)
  const dur = '2.8s'
  const anim = (a: P[], b: P[]) =>
    animated ? (
      <animate attributeName="points" dur={dur} repeatCount="indefinite" values={`${a.map(pt).join(' ')};${b.map(pt).join(' ')};${a.map(pt).join(' ')}`} keyTimes="0;0.5;1" calcMode="spline" keySplines="0.45 0 0.55 1;0.45 0 0.55 1" />
    ) : null
  const Line = ({ k, faded, width }: { k: keyof typeof la; faded?: boolean; width: number }) => (
    <polyline points={la[k].map(pt).join(' ')} fill="none" stroke="currentColor" strokeWidth={width} strokeLinecap="round" strokeLinejoin="round" opacity={faded ? 0.35 : 1}>
      {anim(la[k], lb[k])}
    </polyline>
  )
  return (
    <svg viewBox="0 -4 120 82" className={className} role="img" aria-label={label ?? 'Exercise diagram'}>
      <line x1="4" y1="72" x2="116" y2="72" stroke="var(--line-strong)" strokeWidth="1" />
      {def.prop === 'bench' && <rect x="66" y="56" width="22" height="16" rx="2" fill="var(--raised)" stroke="var(--line-strong)" />}
      {def.prop === 'step' && <rect x="10" y="58" width="20" height="14" rx="2" fill="var(--raised)" stroke="var(--line-strong)" />}
      {def.prop === 'bar' && <line x1="36" y1="8" x2="84" y2="8" stroke="var(--muted)" strokeWidth="2.4" strokeLinecap="round" />}
      {def.prop === 'lowbar' && (
        <>
          <line x1="70" y1="42" x2="100" y2="42" stroke="var(--muted)" strokeWidth="2.4" strokeLinecap="round" />
          <line x1="98" y1="42" x2="98" y2="72" stroke="var(--line-strong)" strokeWidth="1.5" />
        </>
      )}
      <g className="text-faint">
        <Line k="arm2" faded width={3.2} />
        <Line k="leg2" faded width={3.6} />
      </g>
      <g className="text-accent-fg">
        <Line k="leg" width={3.8} />
        <Line k="torso" width={4.6} />
        <Line k="arm" width={3.4} />
        <circle cx={def.a.H[0]} cy={def.a.H[1]} r="4.6" fill="currentColor">
          {animated && (
            <>
              <animate attributeName="cx" dur={dur} repeatCount="indefinite" values={`${def.a.H[0]};${def.b.H[0]};${def.a.H[0]}`} keyTimes="0;0.5;1" calcMode="spline" keySplines="0.45 0 0.55 1;0.45 0 0.55 1" />
              <animate attributeName="cy" dur={dur} repeatCount="indefinite" values={`${def.a.H[1]};${def.b.H[1]};${def.a.H[1]}`} keyTimes="0;0.5;1" calcMode="spline" keySplines="0.45 0 0.55 1;0.45 0 0.55 1" />
            </>
          )}
        </circle>
      </g>
    </svg>
  )
}
